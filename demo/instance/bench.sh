# emit '{json}' -> appends one line to results.jsonl, adding a timestamp.
emit() {
  jq -c --arg ts "$(date -u +%FT%TZ)" '. + {ts: $ts}' <<<"$1" >>"$OUT/results.jsonl"
}

summarize() {
  local dir=$1 f=$1/results.jsonl
  [[ -s "$f" ]] || die "no results in $f"
  {
    echo "<!-- generated by bench.sh from $(basename "$dir")/results.jsonl -->"
    echo
    echo "### Hardware"
    echo
    if [[ -s "$dir/hardware.json" ]]; then
      jq -r '
        "| | |", "|---|---|",
        "| CPU | \(.cpu_model) (\(.sockets) socket(s), \(.host_threads) host threads, \(.threads_per_core) threads/core) |",
        "| CPU slice | \(.slice_cpus) CPUs (\(.cpu_limit_source)), \(.physical_cores) physical cores used for -t |",
        "| ISA | AVX-512: \(.avx512), ik build: \(.ik_variant) |",
        "| RAM | slice \(.ram_slice_gb) GB, host \(.ram_host_gb) GB |",
        "| Memory | \(.memory_desc) |",
        "| GPU | \(.gpu_name), \(.gpu_mem_mib) MiB, PCIe gen \(.pcie_gen) x\(.pcie_width) |",
        "| Driver / CUDA | \(.driver) / \(.cuda) |",
        "| Runtimes | ik \(.ik_ref), mainline \(.mainline_ref) |",
        "| Vast | instance \(.vast_instance) |"' "$dir/hardware.json"
    fi
    echo
    echo "### Download and load"
    echo
    echo "| quant | download GB | download s | MB/s | first load s (ik) | first load s (mainline) |"
    echo "|---|---|---|---|---|---|"
    jq -rs '
      (map(select(.type == "load")) | group_by(.quant + .runtime)
        | map({key: (.[0].quant + "|" + .[0].runtime), value: (min_by(.ts).load_s)}) | from_entries) as $first
      | map(select(.type == "download"))[]
      | "| \(.quant) | \(.gb) | \(.seconds) | \(.mb_per_s) | \($first[.quant + "|ik"] // "-") | \($first[.quant + "|mainline"] // "-") |"
    ' "$f"
    echo
    echo "### Throughput (tokens/s, mean over repeats)"
    echo
    echo "| quant | runtime | -ncmoe | threads | VRAM MiB | context | thinking | prompt tok | prefill t/s | gen tok | gen t/s |"
    echo "|---|---|---|---|---|---|---|---|---|---|---|"
    jq -rs '
      def mean(f): (map(f) | add / length);
      def r1: . * 10 | round / 10;
      map(select(.type == "run" and .ok))
      | group_by([.quant, .runtime, .ncmoe, -.threads, .ctx_order, (.mode != "off"), .mode])[]
      | "| \(.[0].quant) | \(.[0].runtime) | \(.[0].ncmoe) | \(.[0].threads) | \(.[0].vram_mib) | \(.[0].ctx) | \(.[0].mode) | \(mean(.prompt_n) | round) | \(mean(.prompt_tps) | r1) | \(mean(.gen_n) | round) | \(mean(.gen_tps) | r1) |"
    ' "$f"
    echo
    echo "### Best generation speed at 16k context (pass bar: >= 20 t/s on a 4-bit-class quant)"
    echo
    echo "| quant | runtime | -ncmoe | threads | thinking | gen t/s | prefill t/s | pass |"
    echo "|---|---|---|---|---|---|---|---|"
    jq -rs '
      def mean(f): (map(f) | add / length);
      def r1: . * 10 | round / 10;
      map(select(.type == "run" and .ok and .ctx == "16k"))
      | group_by([.quant, .runtime, .ncmoe, .threads, .mode])
      | map({quant: .[0].quant, runtime: .[0].runtime, ncmoe: .[0].ncmoe, threads: .[0].threads,
             mode: .[0].mode, gen: mean(.gen_tps), pp: mean(.prompt_tps)})
      | group_by([.quant, .runtime])[] | max_by(.gen)
      | "| \(.quant) | \(.runtime) | \(.ncmoe) | \(.threads) | \(.mode) | \(.gen | r1) | \(.pp | r1) | \(if (.quant | test("IQ4|Q4")) then (if .gen >= 20 then "yes" else "NO" end) else "n/a (not 4-bit)" end) |"
    ' "$f"
    local failures
    failures=$(jq -s 'map(select((.type == "run" or .type == "load") and (.ok | not))) | length' "$f")
    if [[ "$failures" -gt 0 ]]; then
      echo
      echo "$failures failed loads/requests; see results.jsonl and logs/."
    fi
  } >"$dir/results.md"
  log "wrote $dir/results.md"
}

if [[ -n "$SUMMARIZE_ONLY" ]]; then
  summarize "$SUMMARIZE_ONLY"
  cat "$SUMMARIZE_ONLY/results.md"
  exit 0
fi

command -v jq >/dev/null || die "jq not found"
command -v curl >/dev/null || die "curl not found"
command -v nvidia-smi >/dev/null || die "nvidia-smi not found (no GPU?)"

OUT=${OUT:-/workspace/bench/$(date -u +%Y%m%d-%H%M%S)}
mkdir -p "$OUT/logs" "$OUT/quality" "$OUT/prompts" "$MODELS_DIR"
log "results in $OUT"

