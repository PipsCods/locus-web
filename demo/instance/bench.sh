ctx_order() { case "$1" in short) echo 0 ;; 16k) echo 1 ;; 32k) echo 2 ;; *) echo 9 ;; esac; }

# run_config QUANT RUNTIME MODEL NCMOE THREADS
run_config() {
  local q=$1 rt=$2 model=$3 ncmoe=$4 threads=$5 tag logf vram ctx mode rep code t0 wall max_tokens resp
  tag="$q-$rt-n$ncmoe-t$threads"
  logf=$OUT/logs/$tag.log
  log "config $tag: loading"
  if ! start_server "$rt" "$model" "$ncmoe" "$threads" "$logf"; then
    emit "$(jq -nc --arg q "$q" --arg rt "$rt" --argjson n "$ncmoe" --argjson t "$threads" --argjson l "$LOAD_S" \
      '{type: "load", quant: $q, runtime: $rt, ncmoe: $n, threads: $t, load_s: $l, ok: false}')"
    log "config $tag: server failed to start (see $logf)"
    return 1
  fi
  vram=$(vram_used_mib)
  emit "$(jq -nc --arg q "$q" --arg rt "$rt" --argjson n "$ncmoe" --argjson t "$threads" --argjson l "$LOAD_S" --argjson v "$vram" \
    '{type: "load", quant: $q, runtime: $rt, ncmoe: $n, threads: $t, load_s: $l, vram_mib: $v, ok: true}')"
  log "config $tag: loaded in ${LOAD_S}s, VRAM ${vram} MiB"

  prepare_prompts
  request short off 32 "$OUT/prompts/short.txt" "$OUT/logs/warmup.json" >/dev/null || true

  for ctx in $CONTEXTS; do
    for mode in $MODES; do
      max_tokens=256
      [[ "$mode" == off ]] || max_tokens=1024
      for rep in $(seq "$REPEATS"); do
        resp=$OUT/logs/$tag-$ctx-$mode-$rep.json
        t0=$(now)
        code=$(request "$ctx" "$mode" "$max_tokens" "$OUT/prompts/$ctx.txt" "$resp") || code=000
        wall=$(elapsed "$t0")
        if [[ "$code" == 200 ]] && jq -e '.timings' "$resp" >/dev/null 2>&1; then
          emit "$(jq -c --arg q "$q" --arg rt "$rt" --argjson n "$ncmoe" --argjson t "$threads" \
            --arg ctx "$ctx" --argjson co "$(ctx_order "$ctx")" --arg mode "$mode" --argjson rep "$rep" \
            --argjson v "$vram" --argjson wall "$wall" '
            {type: "run", quant: $q, runtime: $rt, ncmoe: $n, threads: $t, ctx: $ctx, ctx_order: $co,
             mode: $mode, rep: $rep, vram_mib: $v, wall_s: $wall, ok: true,
             prompt_n: .timings.prompt_n, prompt_tps: .timings.prompt_per_second,
             gen_n: .timings.predicted_n, gen_tps: .timings.predicted_per_second,
             finish: .choices[0].finish_reason,
             reasoning_chars: ((.choices[0].message.reasoning_content // "") | length),
             content_chars: ((.choices[0].message.content // "") | length)}' "$resp")"
          log "  $ctx/$mode #$rep: $(jq -r '"pp \(.timings.prompt_n) tok @ \(.timings.prompt_per_second | floor) t/s, tg \(.timings.predicted_n) tok @ \(.timings.predicted_per_second * 10 | round / 10) t/s"' "$resp")"
        else
          emit "$(jq -nc --arg q "$q" --arg rt "$rt" --argjson n "$ncmoe" --argjson t "$threads" \
            --arg ctx "$ctx" --argjson co "$(ctx_order "$ctx")" --arg mode "$mode" --argjson rep "$rep" \
            --arg code "$code" --argjson wall "$wall" \
            '{type: "run", quant: $q, runtime: $rt, ncmoe: $n, threads: $t, ctx: $ctx, ctx_order: $co,
              mode: $mode, rep: $rep, http: $code, wall_s: $wall, ok: false}')"
          log "  $ctx/$mode #$rep: FAILED (HTTP $code, see $resp)"
          if ! kill -0 "$SERVER_PID" 2>/dev/null; then
            log "config $tag: server died"
            SERVER_PID=""
            return 1
          fi
        fi
      done
    done
  done
}

# Smallest -ncmoe whose loaded VRAM use stays under VRAM_TARGET. More CPU
# layers = less VRAM, so this is monotone; binary search over [0, N_LAYERS].
# Sets FILL (not echoed: a $(...) subshell would lose SERVER_PID and die()).
find_fill_ncmoe() {
  local q=$1 rt=$2 model=$3 threads=$4 lo=0 hi=$(( N_LAYERS + 1 )) mid vram ok
  while (( lo < hi )); do
    mid=$(( (lo + hi) / 2 ))
    ok=false
    vram=0
    if start_server "$rt" "$model" "$mid" "$threads" "$OUT/logs/$q-$rt-probe-n$mid.log"; then
      vram=$(vram_used_mib)
      (( vram <= VRAM_TARGET )) && ok=true
    fi
    stop_server
    emit "$(jq -nc --arg q "$q" --arg rt "$rt" --argjson n "$mid" --argjson v "$vram" --argjson l "$LOAD_S" --argjson ok "$ok" \
      '{type: "probe", quant: $q, runtime: $rt, ncmoe: $n, vram_mib: $v, load_s: $l, fits: $ok}')"
    log "probe $rt -ncmoe $mid: VRAM ${vram} MiB, load ${LOAD_S}s, fits=$ok"
    if [[ "$ok" == true ]]; then hi=$mid; else lo=$(( mid + 1 )); fi
  done
  (( lo <= N_LAYERS )) || die "no -ncmoe fits the ${VRAM_TARGET} MiB VRAM target for $q/$rt"
  FILL=$lo
}

# Quality spot check: every prompt x mode, answers saved as markdown.
quality_check() {
  local q=$1 rt=$2 id prompt pf resp mode max_tokens code report
  [[ -s "$PROMPTS_FILE" ]] || { log "no prompts file $PROMPTS_FILE, skipping quality check"; return 0; }
  report=""
  [[ -s "$REPORT_FILE" ]] && report=$(cat "$REPORT_FILE")
  mkdir -p "$OUT/quality/$q"
  while IFS= read -r line; do
    [[ -n "$line" ]] || continue
    id=$(jq -r '.id' <<<"$line")
    prompt=$(jq -r '.prompt' <<<"$line")
    prompt=${prompt//\{\{REPORT\}\}/$report}
    pf=$OUT/quality/$q/$id.prompt.txt
    printf '%s\n' "$prompt" >"$pf"
    for mode in $MODES; do
      max_tokens=2048
      [[ "$mode" == off ]] || max_tokens=6144
      resp=$OUT/quality/$q/$id-$mode.json
      code=$(request quality "$mode" "$max_tokens" "$pf" "$resp") || code=000
      if [[ "$code" == 200 ]]; then
        jq -r --arg id "$id" --arg mode "$mode" --arg q "$q" --arg rt "$rt" '
          "# \($id) (\($q), \($rt), thinking \($mode))\n",
          "_\(.timings.predicted_n) tokens at \(.timings.predicted_per_second * 10 | round / 10) t/s, finish: \(.choices[0].finish_reason)_\n",
          (if (.choices[0].message.reasoning_content // "") != "" then
            "<details><summary>thinking</summary>\n\n\(.choices[0].message.reasoning_content)\n\n</details>\n" else empty end),
          (.choices[0].message.content // "")' "$resp" >"$OUT/quality/$q/$id-$mode.md"
        emit "$(jq -c --arg q "$q" --arg rt "$rt" --arg id "$id" --arg mode "$mode" '
          {type: "quality", quant: $q, runtime: $rt, id: $id, mode: $mode, ok: true,
           gen_n: .timings.predicted_n, gen_tps: .timings.predicted_per_second,
           finish: .choices[0].finish_reason}' "$resp")"
        log "  quality $id/$mode: saved"
      else
        emit "$(jq -nc --arg q "$q" --arg rt "$rt" --arg id "$id" --arg mode "$mode" --arg code "$code" \
          '{type: "quality", quant: $q, runtime: $rt, id: $id, mode: $mode, http: $code, ok: false}')"
        log "  quality $id/$mode: FAILED (HTTP $code)"
      fi
    done
  done <"$PROMPTS_FILE"
}

download_quant() {
  local q=$1 need free t0 secs bytes
  need=${QUANT_GB[$q]:-0}
  free=$(df -BG --output=avail "$MODELS_DIR" | tail -n1 | tr -dc 0-9)
  if [[ ! -d "$MODELS_DIR/$q" ]] && (( free < need + 5 )); then
    die "need ~${need} GB for $q, only ${free} GB free in $MODELS_DIR"
  fi
  log "downloading $q ..."
  t0=$(now)
  hf download "$MODEL_REPO" --include "$q/*" --local-dir "$MODELS_DIR" >"$OUT/logs/download-$q.log" 2>&1 \
    || die "download of $q failed (see $OUT/logs/download-$q.log)"
  secs=$(elapsed "$t0")
  bytes=$(du -sb "$MODELS_DIR/$q" | cut -f1)
  emit "$(jq -nc --arg q "$q" --argjson s "$secs" --argjson b "$bytes" \
    '{type: "download", quant: $q, seconds: $s, gb: ($b / 1e9 * 10 | round / 10),
      mb_per_s: (if $s > 0 then ($b / 1e6 / $s | round) else null end)}')"
  log "downloaded $q: $(( bytes / 1000000000 )) GB in ${secs}s"
}

# ---------------------------------------------------------------------------
# Main loop
# ---------------------------------------------------------------------------

for q in $QUANTS; do
  quality_done=0
  download_quant "$q"
  model=""
  for f in "$MODELS_DIR/$q/$MODEL_STEM-$q-00001-of-"*.gguf; do
    [[ -e "$f" ]] && { model=$f; break; }
  done
  [[ -n "$model" ]] || die "first shard of $q not found under $MODELS_DIR/$q"

  for rt in $RUNTIMES; do
    command -v "llama-server-$rt" >/dev/null || die "llama-server-$rt not on PATH"
    first_threads=${THREADS_LIST%% *}

    if [[ -n "$NCMOE_LIST" ]]; then
      ncmoes=$NCMOE_LIST
    else
      find_fill_ncmoe "$q" "$rt" "$model" "$first_threads"
      fill=$FILL
      log "$q/$rt: fill -ncmoe = $fill"
      ncmoes=$fill
      if [[ "$QUICK" -eq 0 ]] && (( fill + 3 <= N_LAYERS )); then
        ncmoes+=" $(( fill + 3 ))"
      fi
    fi

    # Configs: every threads value at the first ncmoe, plus the other ncmoe
    # values at the first threads value (full grid would double the time).
    configs=()
    first_ncmoe=${ncmoes%% *}
    for t in $THREADS_LIST; do
      configs+=("$first_ncmoe:$t")
      [[ "$QUICK" -eq 1 ]] && break
    done
    for n in ${ncmoes#"$first_ncmoe"}; do
      configs+=("$n:$first_threads")
    done

    for c in "${configs[@]}"; do
      run_config "$q" "$rt" "$model" "${c%%:*}" "${c##*:}" || true
    done

    # Quality check once per quant, on the first runtime that produced results.
    if [[ "$SKIP_QUALITY" -eq 0 && "$quality_done" -eq 0 ]]; then
      # Fastest config at 16k (or whatever ran), thinking off.
      best=$(jq -rs --arg q "$q" --arg rt "$rt" '
        map(select(.type == "run" and .ok and .quant == $q and .runtime == $rt))
        | (map(select(.ctx == "16k")) | if length > 0 then . else null end) as $k
        | ($k // .) | max_by(.gen_tps) // empty | "\(.ncmoe):\(.threads)"' "$OUT/results.jsonl")
      if [[ -n "$best" ]]; then
        log "$q/$rt: quality check with -ncmoe ${best%%:*} -t ${best##*:}"
        if start_server "$rt" "$model" "${best%%:*}" "${best##*:}" "$OUT/logs/$q-$rt-quality.log"; then
          quality_check "$q" "$rt"
          quality_done=1
        else
          log "quality server failed to start"
        fi
      fi
    fi
    stop_server
  done

  summarize "$OUT"
  if [[ "$KEEP_MODELS" -eq 0 ]]; then
    log "deleting $q to free disk"
    rm -rf "${MODELS_DIR:?}/$q"
  fi
done

summarize "$OUT"
cat "$OUT/results.md"
log "done. Copy back with: scp -r <instance>:$OUT ."
