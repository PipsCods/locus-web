SERVER_PID=""
stop_server() {
  if [[ -n "$SERVER_PID" ]] && kill -0 "$SERVER_PID" 2>/dev/null; then
    kill "$SERVER_PID" 2>/dev/null || true
    for _ in $(seq 60); do
      kill -0 "$SERVER_PID" 2>/dev/null || break
      sleep 1
    done
    kill -9 "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
  fi
  SERVER_PID=""
}
trap stop_server EXIT
trap 'exit 130' INT TERM

vram_used_mib() { nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits -i 0 | tr -dc 0-9; }

# Runtime-specific flags, checked against the pinned sources (2026-11-16):
#   ik:       --defer-ple keeps the 28.8 GB n-gram (PLE) table on the mmapped
#             file instead of resident; --jinja is needed because ik defaults
#             to the legacy template path (use_jinja=false) and ignores
#             chat_template_kwargs without it; no -rtr (it disables mmap and
#             repacks, which costs RAM and load time). GGML_CUDA_NO_PINNED=1
#             is set by the llama-server-ik wrapper.
#   mainline: --fit is on by default and would override -ngl/-ncmoe, so
#             --fit off; no --no-op-offload (see BENCHMARK.md).
runtime_flags() {
  case "$1" in
    ik) echo "--defer-ple --jinja $IK_EXTRA" ;;
    mainline) echo "--fit off ${MAINLINE_OP_OFFLOAD_FLAG-} --jinja $MAINLINE_EXTRA" ;;
  esac
}

# start_server RUNTIME MODEL NCMOE THREADS LOGFILE -> sets LOAD_S; returns 1 on failure.
start_server() {
  local rt=$1 model=$2 ncmoe=$3 threads=$4 logf=$5 t0 flags
  stop_server
  PORT=$NEXT_PORT
  NEXT_PORT=$(( NEXT_PORT + 1 ))
  read -r -a flags <<<"$(runtime_flags "$rt")"
  t0=$(now)
  "llama-server-$rt" -m "$model" \
    -ngl 999 -ncmoe "$ncmoe" -t "$threads" \
    -c "$CTX_SIZE" -np 1 \
    --host 127.0.0.1 --port "$PORT" \
    "${flags[@]}" >"$logf" 2>&1 &
  SERVER_PID=$!
  local deadline=$(( $(date +%s) + LOAD_TIMEOUT ))
  while (( $(date +%s) < deadline )); do
    if ! kill -0 "$SERVER_PID" 2>/dev/null; then
      wait "$SERVER_PID" 2>/dev/null || true
      SERVER_PID=""
      LOAD_S=$(elapsed "$t0")
      return 1
    fi
    if [[ "$(curl -s --max-time 2 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/health")" == 200 ]]; then
      LOAD_S=$(elapsed "$t0")
      return 0
    fi
    sleep 2
  done
  LOAD_S=$(elapsed "$t0")
  stop_server
  return 1
}

