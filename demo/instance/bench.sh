#!/usr/bin/env bash
# locus benchmark: Qwen3.8-Flash-Next in hybrid CPU/GPU mode on one GPU (RTX 5090, RTX 3090, ...).
# Runs ON the rented machine (inside the locus instance image), over ssh.
#
# For each quant: download (timed), then for each runtime:
#   1. find the -ncmoe that fills the GPU to ~VRAM_TARGET_MIB (binary search
#      over server loads, each load timed),
#   2. sweep a few (ncmoe, threads) configs, measuring prefill and generation
#      tokens/s through llama-server at short / 16k / 32k prompt length, with
#      thinking off and low,
#   3. (once per quant, first runtime that works) a quality spot check: prompts from a file, answers
#      saved as markdown.
# Results: results.jsonl (one JSON object per measurement), results.md
# (tables to paste into demo/BENCHMARK.md), hardware.json, logs/, quality/.
#
# Usage: bench.sh [options]
#   --quants "Q ..."        default: UD-IQ4_XS, UD-Q4_K_XL (only if RAM >= 190 GB)
#   --runtimes "R ..."      default: "ik mainline"
#   --contexts "C ..."      default: "short 16k 32k"
#   --modes "M ..."         thinking modes, default: "off low"
#   --repeats N             requests per (context, mode), default 2
#   --ncmoe "N ..."         skip the search and use these -ncmoe values
#   --threads "T ..."       default: physical cores of the slice, and half
#   --vram-target MiB       VRAM to fill, default GPU memory minus 3100 MiB (29500 on a 5090)
#   --models-dir DIR        default /workspace/models
#   --out DIR               default /workspace/bench/<UTC timestamp>
#   --prompts FILE          quality prompts (JSONL: {"id","prompt"}), default prompts/spot-check.jsonl
#   --report FILE           text substituted for {{REPORT}}, default prompts/sample-report.txt
#   --skip-quality          no quality spot check
#   --keep-models           do not delete a quant after benchmarking it
#   --quick                 repeats 1, one config per runtime (fill ncmoe, physical threads)
#   --hw-only               only record hardware facts and exit
#   --summarize DIR         only rebuild results.md from DIR/results.jsonl
#
# Env: MAINLINE_OP_OFFLOAD_FLAG=--no-op-offload adds that flag back to mainline (it cost ~40% prefill in the benchmark).
# Env: IK_EXTRA / MAINLINE_EXTRA append flags to every server start of that
# runtime (e.g. IK_EXTRA="-ub 2048 -b 2048"). HF_TOKEN is used if set.
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

MODEL_REPO=${MODEL_REPO_BENCH:-unsloth/Qwen3.8-Flash-Next-GGUF}
MODEL_STEM=Qwen3.8-Flash-Next
N_LAYERS=48   # qwen4exp.block_count in the GGUF

QUANTS=""
RUNTIMES="ik mainline"
CONTEXTS="short 16k 32k"
MODES="off low"
REPEATS=2
NCMOE_LIST=""
THREADS_LIST=""
VRAM_TARGET=""
MODELS_DIR=/workspace/models
OUT=""
PROMPTS_FILE=$SCRIPT_DIR/prompts/spot-check.jsonl
REPORT_FILE=$SCRIPT_DIR/prompts/sample-report.txt
SKIP_QUALITY=0
KEEP_MODELS=0
QUICK=0
HW_ONLY=0
SUMMARIZE_ONLY=""

NEXT_PORT=8090
CTX_SIZE=40960          # room for a 32k prompt plus thinking
LOAD_TIMEOUT=1800
REQUEST_TIMEOUT=1800
IK_EXTRA=${IK_EXTRA:-}
MAINLINE_EXTRA=${MAINLINE_EXTRA:-}

# Sizes in GB from the unsloth repo (each includes the 28.8 GB IQ4_NL n-gram
# table shard), used for the disk check only.
declare -A QUANT_GB=([UD-Q2_K_XL]=79 [UD-Q3_K_XL]=90 [UD-IQ4_XS]=94 [UD-Q4_K_XL]=112)

usage() { sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'; }
log() { printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }
now() { date +%s.%N; }
elapsed() { awk -v a="$1" -v b="$(now)" 'BEGIN { printf "%.1f", b - a }'; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --quants) QUANTS=${2:?}; shift ;;
    --runtimes) RUNTIMES=${2:?}; shift ;;
    --contexts) CONTEXTS=${2:?}; shift ;;
    --modes) MODES=${2:?}; shift ;;
    --repeats) REPEATS=${2:?}; shift ;;
    --ncmoe) NCMOE_LIST=${2:?}; shift ;;
    --threads) THREADS_LIST=${2:?}; shift ;;
    --vram-target) VRAM_TARGET=${2:?}; shift ;;
    --models-dir) MODELS_DIR=${2:?}; shift ;;
    --out) OUT=${2:?}; shift ;;
    --prompts) PROMPTS_FILE=${2:?}; shift ;;
    --report) REPORT_FILE=${2:?}; shift ;;
    --skip-quality) SKIP_QUALITY=1 ;;
    --keep-models) KEEP_MODELS=1 ;;
    --quick) QUICK=1 ;;
    --hw-only) HW_ONLY=1 ;;
    --summarize) SUMMARIZE_ONLY=${2:?}; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
  shift
done

if [[ "$QUICK" -eq 1 ]]; then
  REPEATS=1
fi

