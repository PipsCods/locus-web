lscpu_field() { lscpu | awk -F: -v k="$1" '$1 == k { sub(/^[ \t]+/, "", $2); print $2; exit }'; }

# CPUs this container may use: cgroup v2 cpu.max, then v1 CFS quota, then cpuset.
slice_cpus() {
  local q p available
  available=$(nproc)
  if [[ -r /sys/fs/cgroup/cpu.max ]]; then
    read -r q p </sys/fs/cgroup/cpu.max
  elif [[ -r /sys/fs/cgroup/cpu/cpu.cfs_quota_us ]]; then
    q=$(cat /sys/fs/cgroup/cpu/cpu.cfs_quota_us)
    p=$(cat /sys/fs/cgroup/cpu/cpu.cfs_period_us)
  fi
  if [[ "${q:-}" =~ ^[0-9]+$ ]] && (( q > 0 && q < available * p )); then
    echo "$(( q / p )) quota"
  else
    echo "$available cpuset"
  fi
}

# Memory limit of this container in bytes (or the host total if unlimited).
slice_ram_bytes() {
  local host lim=""
  host=$(awk '/^MemTotal:/ { print $2 * 1024 }' /proc/meminfo)
  if [[ -r /sys/fs/cgroup/memory.max ]]; then
    lim=$(cat /sys/fs/cgroup/memory.max)
  elif [[ -r /sys/fs/cgroup/memory/memory.limit_in_bytes ]]; then
    lim=$(cat /sys/fs/cgroup/memory/memory.limit_in_bytes)
  fi
  if [[ "$lim" =~ ^[0-9]+$ ]] && [[ "$lim" -lt "$host" ]]; then
    echo "$lim"
  else
    echo "$host"
  fi
}

# DIMM count / type / speed. Needs dmidecode and /dev/mem or sysfs DMI access,
# which a container often lacks; then we say so instead of guessing.
memory_desc() {
  local dmi
  if dmi=$(dmidecode -t memory 2>/dev/null) && grep -q 'Memory Device' <<<"$dmi"; then
    awk '
      /^Memory Device/ { dev = 1; size = ""; type = ""; speed = ""; cspeed = "" }
      dev && /^\tSize:/ { size = $0; sub(/^\tSize: /, "", size) }
      dev && /^\tType:/ { type = $2 }
      dev && /^\tSpeed:/ { speed = $2 " " $3 }
      dev && /^\tConfigured Memory Speed:/ { cspeed = $4 " " $5 }
      dev && /^$/ {
        if (size != "" && size !~ /No Module/) { n++; t = type; s = size; sp = speed; cs = cspeed }
        dev = 0
      }
      END {
        if (n) printf "%d DIMMs populated, %s %s, rated %s, configured %s\n", n, s, t, sp, cs
        else print "dmidecode: no populated DIMMs reported"
      }' <<<"$dmi"
  else
    echo "not readable in this container (dmidecode needs DMI access)"
  fi
}

record_hardware() {
  local cpus src threads_per_core phys gpu ik_variant
  read -r cpus src < <(slice_cpus)
  threads_per_core=$(lscpu_field "Thread(s) per core")
  threads_per_core=${threads_per_core:-1}
  phys=$(( cpus / threads_per_core ))
  (( phys >= 1 )) || phys=1
  PHYS_CORES=$phys
  RAM_SLICE_GB=$(( $(slice_ram_bytes) / 1000000000 ))

  gpu=$(nvidia-smi --query-gpu=name,memory.total,driver_version,pcie.link.gen.max,pcie.link.width.max \
        --format=csv,noheader,nounits -i 0)
  ik_variant=$(llama-server-ik --locus-variant 2>/dev/null || echo '?')

  jq -n \
    --arg cpu_model "$(lscpu_field 'Model name')" \
    --arg sockets "$(lscpu_field 'Socket(s)')" \
    --arg host_threads "$(lscpu_field 'CPU(s)')" \
    --arg threads_per_core "$threads_per_core" \
    --arg numa "$(lscpu_field 'NUMA node(s)')" \
    --arg l3 "$(lscpu_field 'L3 cache')" \
    --arg slice_cpus "$cpus" --arg cpu_limit_source "$src" \
    --arg physical_cores "$phys" \
    --arg avx512 "$(grep -qw avx512f /proc/cpuinfo && echo yes || echo no)" \
    --arg ik_variant "$ik_variant" \
    --arg ram_slice_gb "$RAM_SLICE_GB" \
    --arg ram_host_gb "$(awk '/^MemTotal:/ { printf "%d", $2 * 1024 / 1e9 }' /proc/meminfo)" \
    --arg memory_desc "$(memory_desc)" \
    --arg gpu_name "$(cut -d, -f1 <<<"$gpu" | xargs)" \
    --arg gpu_mem_mib "$(cut -d, -f2 <<<"$gpu" | xargs)" \
    --arg driver "$(cut -d, -f3 <<<"$gpu" | xargs)" \
    --arg pcie_gen "$(cut -d, -f4 <<<"$gpu" | xargs)" \
    --arg pcie_width "$(cut -d, -f5 <<<"$gpu" | xargs)" \
    --arg cuda "$(nvidia-smi | sed -n 's/.*CUDA Version: *\([0-9.]*\).*/\1/p' | head -n1)" \
    --arg ik_ref "$(cut -c1-12 /opt/ik/REF 2>/dev/null || echo '?')" \
    --arg mainline_ref "$(cut -c1-12 /opt/mainline/REF 2>/dev/null || echo '?')" \
    --arg vast_instance "${CONTAINER_ID:-?}" \
    --arg disk_free_gb "$(df -BG --output=avail "$MODELS_DIR" | tail -n1 | tr -dc 0-9)" \
    '$ARGS.named' >"$OUT/hardware.json"
  {
    lscpu
    echo
    nvidia-smi
    echo
    nvidia-smi -q -d CLOCK,POWER,PCIE 2>/dev/null || true
    echo
    cat /proc/meminfo
    echo
    numactl --hardware 2>/dev/null || true
  } >"$OUT/hardware.txt" 2>&1
  emit "$(jq -c '{type: "hardware"} + .' "$OUT/hardware.json")"
  log "hardware: $(jq -r '"\(.cpu_model) | slice \(.slice_cpus) CPUs, \(.physical_cores) phys | \(.ram_slice_gb) GB | \(.gpu_name) \(.driver)"' "$OUT/hardware.json")"
}

record_hardware
if [[ -z "$VRAM_TARGET" ]]; then
  # leave ~3 GB for compute buffers and the 32k KV cache, as measured on the 5090
  VRAM_TARGET=$(( $(jq -r '.gpu_mem_mib' "$OUT/hardware.json") - 3100 ))
  log "VRAM target ${VRAM_TARGET} MiB"
fi
if [[ "$HW_ONLY" -eq 1 ]]; then
  cat "$OUT/hardware.json"
  exit 0
fi

if [[ -z "$THREADS_LIST" ]]; then
  half=$(( PHYS_CORES / 2 ))
  THREADS_LIST=$PHYS_CORES
  if (( half >= 1 && half != PHYS_CORES )); then
    THREADS_LIST+=" $half"
  fi
fi
if [[ -z "$QUANTS" ]]; then
  QUANTS="UD-IQ4_XS"
  if (( RAM_SLICE_GB >= 190 )); then
    QUANTS+=" UD-Q4_K_XL"
  else
    log "slice RAM ${RAM_SLICE_GB} GB < 190 GB: skipping UD-Q4_K_XL"
  fi
fi
log "quants: $QUANTS | runtimes: $RUNTIMES | threads: $THREADS_LIST | contexts: $CONTEXTS | modes: $MODES"

