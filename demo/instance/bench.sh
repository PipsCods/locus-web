# Deterministic filler: report-like sentences built from fixed word lists.
make_filler() {
  awk -v n="$1" 'BEGIN {
    srand(42)
    split("revenue margin backlog supplier plant contract inventory customer warranty forecast pipeline region segment budget headcount invoice shipment tariff capacity order", nouns, " ")
    split("increased declined stabilised recovered slipped improved widened narrowed accelerated stalled", verbs, " ")
    split("quarter month week year period cycle", spans, " ")
    for (i = 0; i < n; i++) {
      printf "In the %s %d, %s in unit %d %s by %.1f%% while %s at site %d %s to %d.%s",
        spans[int(rand() * 6) + 1], int(rand() * 12) + 1,
        nouns[int(rand() * 20) + 1], int(rand() * 900) + 100, verbs[int(rand() * 10) + 1], rand() * 30,
        nouns[int(rand() * 20) + 1], int(rand() * 90) + 10, verbs[int(rand() * 10) + 1], int(rand() * 99000) + 1000,
        (i % 6 == 5) ? "\n" : " "
    }
  }'
}

QUESTION="In three sentences, what does the document above describe? Then name the single largest number it mentions."

count_tokens() {
  jq -n --rawfile c "$1" '{content: $c}' \
    | curl -sf --max-time 300 "http://127.0.0.1:$PORT/tokenize" -H 'Content-Type: application/json' -d @- \
    | jq '.tokens | length'
}

# Build $OUT/prompts/{short,16k,32k}.txt once, sized with the server's tokenizer.
prepare_prompts() {
  [[ -s "$OUT/prompts/32k.txt" ]] && return 0
  printf 'Write a haiku about a cold server room, then explain it in one sentence.\n' >"$OUT/prompts/short.txt"
  local target label sentences=1200 tokens f
  for label in 16k 32k; do
    case "$label" in 16k) target=16000 ;; 32k) target=32000 ;; esac
    f=$OUT/prompts/$label.txt
    for _ in 1 2 3 4; do
      { echo "<document>"; make_filler "$sentences"; echo "</document>"; echo; echo "$QUESTION"; } >"$f"
      tokens=$(count_tokens "$f") || die "tokenize failed"
      if (( tokens >= target - 300 && tokens <= target + 300 )); then break; fi
      sentences=$(( sentences * target / tokens ))
    done
    log "prompt $label: $tokens tokens"
  done
}

# request CTX MODE MAX_TOKENS PROMPT_FILE OUTFILE -> response JSON in OUTFILE
request() {
  local mode=$2 max_tokens=$3 pf=$4 outf=$5 kwargs sampling
  case "$mode" in
    # Chat template (GGUF tokenizer.chat_template): thinking is off only via
    # enable_thinking=false; reasoning_effort accepts xhigh (default), medium,
    # low. "none" is not a template level and would raise.
    off) kwargs='{"enable_thinking": false}'
         sampling='{"temperature": 0.7, "top_p": 0.8, "top_k": 20, "min_p": 0, "presence_penalty": 1.5}' ;;
    low|medium|xhigh)
         kwargs=$(jq -nc --arg e "$mode" '{reasoning_effort: $e}')
         sampling='{"temperature": 1.0, "top_p": 0.95, "top_k": 20, "min_p": 0, "presence_penalty": 0}' ;;
    *) die "unknown mode $mode" ;;
  esac
  jq -n --rawfile p "$pf" --argjson kw "$kwargs" --argjson s "$sampling" --argjson mt "$max_tokens" '
    {messages: [{role: "user", content: $p}], max_tokens: $mt, stream: false,
     cache_prompt: false, seed: 1234, chat_template_kwargs: $kw} + $s' \
    | curl -s --max-time "$REQUEST_TIMEOUT" "http://127.0.0.1:$PORT/v1/chat/completions" \
        -H 'Content-Type: application/json' -d @- -o "$outf" -w '%{http_code}'
}

