#!/usr/bin/env bash
# locus multi-user benchmark: how one hybrid CPU/GPU server holds up as more
# people use it at once, and which serving options help.
# Runs ON the rented machine, after bench.sh (it reuses bench.sh's model files
# and its -ncmoe "fill" values).
#
# For each server config (CONFIGS below): start llama-server, then for each
# workload and number of simultaneous users run loadgen.py (closed loop: every
# user sends the next request as soon as the previous answer ends) and record
# aggregate tokens/s, tokens/s per user, time to first token and latency.
#
# Usage: bench-concurrency.sh --model GGUF --ncmoe "ik=N mainline=M" [options]
#   --model FILE         first shard of the quant to serve
#   --ncmoe "ik=N mainline=M"   -ncmoe per runtime (bench.sh's fill values)
#   --threads N          default: physical cores of the slice
#   --users "U ..."      default "1 2 4 8"
#   --workloads "W ..."  default "chat doc shared-doc"
#   --rounds N           requests per user per run, default 2
#   --max-tokens N       answer length (fixed with ignore_eos), default 256
#   --configs "NAME ..." run only these configs (default: all)
#   --out DIR            default /workspace/bench/concurrency-<UTC timestamp>
#   --report FILE        default prompts/sample-report.txt
#   --mtp-head FILE      MTP draft head GGUF (MTP/mtp-Qwen3.8-Flash-Next-shared-Q8_0.gguf);
#                        without it the mtp configs are skipped
#   --mtp-head-full FILE self-contained head (MTP/mtp-Qwen3.8-Flash-Next-Q8_0.gguf) for
#                        mainline, which cannot borrow the shared head's missing tensors
#   --summarize DIR      only rebuild results.md from DIR/results.jsonl
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# every server start gets a fresh port: closed connections keep the previous
# port busy for up to a minute, and mainline then fails with "couldn't bind"
PORT=8080
NEXT_PORT=8080
CTX_PER_SLOT=8192   # the doc workload needs ~2.5k; room for a longer chat

# name | runtime | slots | extra flags
# Flags checked against the pinned builds' --help. Each config changes one
# thing from its base, so each effect can be read off:
#   1slot      one request at a time: further users queue
#   8slots     8 parallel slots, continuous batching (on by default in both)
#   ub2048     bigger batches: more prompt tokens per GPU pass when several
#              users send documents at once
#   nocram     host-RAM prompt cache off (-cram 0; on by default, 8 GiB): it is
#              what lets one user's read of the shared report serve the next
#   kvu        mainline only: one KV pool shared by all slots instead of a
#              fixed share each (unified is the default only when -np is auto)
#   mtp        speculative decoding with the model's MTP head (MTP_HEAD), which
#              guesses 2 tokens ahead and the main model checks them
CONFIGS=(
  "ik-1slot|ik|1|"
  "ik-1slot-mtp|ik|1|MTP"
  "ik-8slots|ik|8|"
  "ik-8slots-ub2048|ik|8|-b 4096 -ub 2048"
  "ik-8slots-nocram|ik|8|-cram 0"
  "ik-8slots-mtp|ik|8|MTP"
  "mainline-1slot|mainline|1|"
  "mainline-1slot-mtp|mainline|1|MTP"
  "mainline-8slots|mainline|8|"
  "mainline-8slots-kvu|mainline|8|--kv-unified"
  "mainline-8slots-ub2048|mainline|8|-b 4096 -ub 2048"
  "mainline-8slots-nocram|mainline|8|-cram 0"
  "mainline-8slots-mtp|mainline|8|MTP"
)
# MTP flags per runtime (MTP in a config above is replaced by these)
mtp_flags() {
  case "$1" in
    ik) echo "-md $MTP_HEAD --spec-type mtp:n_max=2,p_min=0.0" ;;
    mainline) echo "-md $MTP_HEAD_FULL --spec-type draft-mtp --spec-draft-n-max 2" ;;
  esac
}

MODEL=""
NCMOE_SPEC=""
THREADS=""
USERS="1 2 4 8"
WORKLOADS="chat doc shared-doc"
ROUNDS=2
MAX_TOKENS=256
ONLY=""
OUT=""
REPORT=$SCRIPT_DIR/prompts/sample-report.txt
SUMMARIZE=""
MTP_HEAD=""
MTP_HEAD_FULL=""

die() { echo "error: $*" >&2; exit 1; }
log() { echo "[$(date -u +%H:%M:%S)] $*" | tee -a "$OUT/run.log" >&2; }

while (($#)); do
  case "$1" in
    --model) MODEL=${2:?}; shift ;;
    --ncmoe) NCMOE_SPEC=${2:?}; shift ;;
    --threads) THREADS=${2:?}; shift ;;
    --users) USERS=${2:?}; shift ;;
    --workloads) WORKLOADS=${2:?}; shift ;;
    --rounds) ROUNDS=${2:?}; shift ;;
    --max-tokens) MAX_TOKENS=${2:?}; shift ;;
    --configs) ONLY=${2:?}; shift ;;
    --out) OUT=${2:?}; shift ;;
    --report) REPORT=${2:?}; shift ;;
    --summarize) SUMMARIZE=${2:?}; shift ;;
    --mtp-head) MTP_HEAD=${2:?}; shift ;;
    --mtp-head-full) MTP_HEAD_FULL=${2:?}; shift ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
  shift
done

summarize() {
  local dir=$1
  {
    echo "<!-- generated by bench-concurrency.sh from $(basename "$dir")/results.jsonl -->"
    echo
    echo "| config | ncmoe | workload | users | aggregate gen t/s | per-user gen t/s | TTFT mean s | TTFT p95 s | latency mean s | cached prompt tok | failed |"
    echo "|---|---|---|---|---|---|---|---|---|---|---|"
    jq -r 'select(.type == "run") | [.config, .ncmoe, .s.workload, .s.users, .s.aggregate_gen_tps, .s.per_user_gen_tps_mean, .s.ttft_mean_s, .s.ttft_p95_s, .s.latency_mean_s, .s.cache_hit_tokens_mean, .s.failed] | map(tostring) | "| " + join(" | ") + " |"' "$dir/results.jsonl"
    echo
    echo "Speculative decoding (last acceptance line in the server log):"
    jq -r 'select(.type == "spec") | "- \(.config): \(.acceptance)"' "$dir/results.jsonl"
    echo
    echo "Configs that did not start:"
    jq -r 'select(.type == "start_failed") | "- \(.config): \(.reason)"' "$dir/results.jsonl"
  } >"$dir/results.md"
}

if [[ -n "$SUMMARIZE" ]]; then summarize "$SUMMARIZE"; cat "$SUMMARIZE/results.md"; exit 0; fi

[[ -f "$MODEL" ]] || die "--model must be an existing GGUF file"
[[ -n "$NCMOE_SPEC" ]] || die "--ncmoe \"ik=N mainline=M\" is required"
[[ -s "$REPORT" ]] || die "report file not found: $REPORT"
declare -A NCMOE
for kv in $NCMOE_SPEC; do NCMOE[${kv%%=*}]=${kv#*=}; done
if [[ -z "$THREADS" ]]; then
  THREADS=$(lscpu -p=CORE,ONLINE 2>/dev/null | grep -v '^#' | awk -F, '$2=="Y"{print $1}' | sort -u | wc -l)
  quota=$(awk '{ if ($1 != "max") printf "%d", $1/$2 }' /sys/fs/cgroup/cpu.max 2>/dev/null || true)
  if [[ -n "$quota" && "$quota" -gt 0 ]]; then THREADS=$(( quota / 2 )); fi
fi
OUT=${OUT:-/workspace/bench/concurrency-$(date -u +%Y%m%d-%H%M%S)}
mkdir -p "$OUT/logs"
: >"$OUT/results.jsonl"
PY=$(command -v python3)
[[ -x /opt/venv/bin/python3 ]] && PY=/opt/venv/bin/python3

SERVER_PID=""
stop_server() {
  if [[ -n "$SERVER_PID" ]]; then kill "$SERVER_PID" 2>/dev/null || true; wait "$SERVER_PID" 2>/dev/null || true; SERVER_PID=""; fi
  # the wrapper's child can outlive the wrapper while it shuts down and keeps
  # the port bound (it stops answering /health first): wait for the process
  # itself, then force it, or the next server fails with "couldn't bind"
  local i
  for i in $(seq 1 30); do
    pgrep -f -- "llama-server.*--port $PORT" >/dev/null || break
    (( i == 1 )) && pkill -f -- "llama-server.*--port $PORT" 2>/dev/null
    (( i == 20 )) && pkill -9 -f -- "llama-server.*--port $PORT" 2>/dev/null
    sleep 1
  done
  sleep 2
}
trap stop_server EXIT

# start RUNTIME SLOTS NCMOE EXTRA LOG -> 0 when /health answers
start_server() {
  local rt=$1 slots=$2 ncmoe=$3 extra=$4 logf=$5 base deadline
  stop_server
  PORT=$NEXT_PORT
  NEXT_PORT=$(( NEXT_PORT + 1 ))
  case "$rt" in
    ik) base="--defer-ple --jinja" ;;
    mainline) base="--fit off --jinja" ;;
  esac
  # shellcheck disable=SC2086  # flag lists
  "llama-server-$rt" -m "$MODEL" -ngl 999 -ncmoe "$ncmoe" -t "$THREADS" \
    -np "$slots" -c $(( CTX_PER_SLOT * slots )) --host 127.0.0.1 --port "$PORT" \
    $base $extra >"$logf" 2>&1 &
  SERVER_PID=$!
  deadline=$(( $(date +%s) + 600 ))
  while (( $(date +%s) < deadline )); do
    kill -0 "$SERVER_PID" 2>/dev/null || { wait "$SERVER_PID" 2>/dev/null || true; SERVER_PID=""; return 1; }
    [[ "$(curl -s --max-time 2 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/health")" == 200 ]] && return 0
    sleep 2
  done
  stop_server
  return 1
}

log "model $(basename "$MODEL") | threads $THREADS | users: $USERS | workloads: $WORKLOADS | rounds $ROUNDS | max tokens $MAX_TOKENS"
for spec in "${CONFIGS[@]}"; do
  IFS='|' read -r name rt slots extra <<<"$spec"
  if [[ -n "$ONLY" && " $ONLY " != *" $name "* ]]; then continue; fi
  if [[ "$extra" == MTP ]]; then
    if [[ "$rt" == ik && ! -f "$MTP_HEAD" ]]; then
      log "$name: no --mtp-head, skipping"
      continue
    fi
    if [[ "$rt" == mainline && ! -f "$MTP_HEAD_FULL" ]]; then
      log "$name: no --mtp-head-full, skipping"
      continue
    fi
    extra=$(mtp_flags "$rt")
  fi
  ncmoe=${NCMOE[$rt]:-}
  [[ -n "$ncmoe" ]] || { log "$name: no -ncmoe for $rt, skipping"; continue; }
  # More slots and bigger batches need more VRAM for buffers: if the fill value
  # does not start, move two more expert layers to the CPU, up to three times.
  started=false
  for try in 0 1 2 3; do
    n=$(( ncmoe + 2 * try ))
    log "$name: starting ($rt, $slots slots, -ncmoe $n${extra:+, $extra})"
    if start_server "$rt" "$slots" "$n" "$extra" "$OUT/logs/$name-n$n.log"; then started=true; break; fi
    log "$name: did not start at -ncmoe $n (tail: $(tail -n 2 "$OUT/logs/$name-n$n.log" | tr '\n' ' ' | cut -c1-200))"
  done
  if [[ "$started" != true ]]; then
    jq -nc --arg c "$name" --arg r "no start up to -ncmoe $n" '{type: "start_failed", config: $c, reason: $r}' >>"$OUT/results.jsonl"
    continue
  fi
  for w in $WORKLOADS; do
    for u in $USERS; do
      # one slot serves one request at a time: past 1 user, the others queue
      res=$("$PY" -I "$SCRIPT_DIR/loadgen.py" --port "$PORT" --workload "$w" --users "$u" --rounds "$ROUNDS" \
        --max-tokens "$MAX_TOKENS" --report "$REPORT") || { log "$name/$w/$u: loadgen failed"; continue; }
      echo "$res" >"$OUT/logs/$name-$w-u$u.json"
      jq -c --arg c "$name" --arg rt "$rt" --argjson slots "$slots" --argjson n "$n" --arg extra "$extra" \
        '{type: "run", config: $c, runtime: $rt, slots: $slots, ncmoe: $n, extra: $extra, s: .summary}' <<<"$res" >>"$OUT/results.jsonl"
      log "$name/$w/$u users: $(jq -r '.summary | "aggregate \(.aggregate_gen_tps) t/s, per user \(.per_user_gen_tps_mean) t/s, TTFT \(.ttft_mean_s)s (p95 \(.ttft_p95_s)), failed \(.failed)"' <<<"$res")"
    done
  done
  if [[ "$extra" == *spec-type* ]]; then
    acc=$(sed -n 's/.*draft acceptance/draft acceptance/p' "$OUT/logs/$name-n$n.log" | tail -n 1 | cut -c1-120)
    log "$name: ${acc:-no draft acceptance line in the log: speculation may not have run}"
    jq -nc --arg c "$name" --arg a "${acc:-none}" '{type: "spec", config: $c, acceptance: $a}' >>"$OUT/results.jsonl"
  fi
  stop_server
done
summarize "$OUT"
log "done: $OUT/results.md"
