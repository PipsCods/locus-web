// Refreshes the vendored mailbox blocklists in src/checks/lists/ from their upstream projects.
// Run with `npm run lists:update`, review the diff, commit. The Worker never fetches these lists
// at runtime: a snapshot keeps the checks deterministic and costs no subrequests.
//
//   disposable.js  <- github.com/disposable-email-domains/disposable-email-domains (CC0 1.0)
//   free.js        <- github.com/Kikobeats/free-email-domains (MIT; derived from HubSpot's list)

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../src/checks/lists/", import.meta.url));
const SOURCES = {
  disposable: {
    list: "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf",
    license: "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/LICENSE.txt",
    parse: (text) => text.split("\n"),
  },
  free: {
    list: "https://raw.githubusercontent.com/Kikobeats/free-email-domains/master/domains.json",
    license: "https://raw.githubusercontent.com/Kikobeats/free-email-domains/master/LICENSE.md",
    parse: (text) => JSON.parse(text),
  },
};

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const DOMAIN = /^[a-z0-9.-]+\.[a-z0-9-]{2,}$/;

for (const [name, src] of Object.entries(SOURCES)) {
  const domains = [...new Set(src.parse(await get(src.list)).map((d) => String(d).trim().toLowerCase()).filter((d) => DOMAIN.test(d)))].sort();
  if (domains.length < 1000) throw new Error(`${name}: only ${domains.length} domains, refusing to write`);
  const header = `// Generated by scripts/update-blocklists.mjs on ${new Date().toISOString().slice(0, 10)} from\n// ${src.list}\n// License: see ${name}.LICENSE. Do not edit by hand.\n`;
  await writeFile(`${OUT}${name}.js`, `${header}export default ${JSON.stringify(domains.join("\n"))};\n`);
  await writeFile(`${OUT}${name}.LICENSE`, await get(src.license));
  console.log(`${name}: ${domains.length} domains`);
}
